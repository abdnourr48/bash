from playwright.sync_api import sync_playwright
from pathlib import Path
base='http://127.0.0.1:8765/'
errors=[]
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-dev-shm-usage'])
 page=browser.new_page(viewport={'width':1440,'height':900},device_scale_factor=1)
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto(base,wait_until='load',timeout=20000)
 print('title:',page.title())
 print('view:',page.locator('.view:not([hidden])').count())
 print('lessons:',page.locator('.lesson-card').count(),'modules:',page.locator('.module-btn').count())
 page.screenshot(path='/mnt/data/Bash-Academy-v9-Preview.png',full_page=False)
 page.locator('.lesson-card').first.click()
 print('lesson:',page.locator('#lessonReader').is_visible(),page.locator('#lessonReader h2').inner_text())
 page.locator('#runLesson').click()
 print('lesson run:',page.locator('#lessonOutput').inner_text()[:120])
 page.locator('#completeLesson').click()
 print('progress:',page.locator('#completedLessons').inner_text())
 page.locator('[data-view="reference"]').click()
 print('commands visible:',page.locator('.command-card').count())
 page.locator('#cmdSearch').fill('grep')
 print('grep filtered:',page.locator('#referenceCount').inner_text())
 page.locator('.command-card').first.click()
 print('dialog:',page.locator('#commandDialog').is_visible())
 page.locator('#dialogClose').click()
 page.locator('[data-view="lab"]').click()
 page.locator('#commandInput').fill('cat names.txt | sort | uniq > unique.txt')
 page.locator('#terminalForm button[type="submit"]').click()
 print('file unique:',page.locator('#fileTree .file-entry').filter(has_text='unique.txt').count())
 page.locator('#commandInput').fill('cat unique.txt')
 page.locator('#terminalForm button[type="submit"]').click()
 print('console:',page.locator('#termOutput').inner_text()[-280:])
 page.screenshot(path='/mnt/data/Bash-Academy-v9-Lab.png',full_page=False)
 page.locator('[data-view="practice"]').click()
 print('missions',page.locator('.mission-item').count())
 page.locator('#missionStart').click()
 print('lab after mission prepare',page.locator('#commandInput').input_value())
 page.locator('#commandInput').fill('mkdir projects')
 page.locator('#terminalForm button[type="submit"]').click()
 page.locator('[data-view="practice"]').click()
 page.locator('#missionCheck').click()
 print('mission verify:',page.locator('#missionFeedback').inner_text()[:100])
 page.locator('#lang').select_option('fr')
 print('fr title:',page.locator('#hero-title').inner_text())
 page.locator('#lang').select_option('en')
 print('en title:',page.locator('#hero-title').inner_text())
 page.locator('#lang').select_option('ar')
 page.locator('#theme').click()
 print('dark:',page.locator('html').get_attribute('data-theme'))
 mobile=browser.new_page(viewport={'width':390,'height':844},device_scale_factor=1,is_mobile=True,has_touch=True)
 mobile.on('pageerror',lambda e:errors.append(str(e)))
 mobile.goto(base,wait_until='load')
 mobile.screenshot(path='/mnt/data/Bash-Academy-v9-Mobile.png',full_page=False)
 print('mobile overflow:',mobile.evaluate('document.documentElement.scrollWidth > window.innerWidth'))
 print('mobile title:',mobile.locator('#hero-title').inner_text())
 print('js errors:',errors)
 browser.close()
if errors: raise SystemExit('JS errors detected')
